// ======================================
// APPLY FILTER
// ======================================

function applyCurrentFilter(){

    const search =
        nameSearch.value
        .trim()
        .toLowerCase();


    let list =
        [...namesOfAllah];


    if(search){

        list =
            list.filter(
                function(name){

                    return (

                        name.english
                        .toLowerCase()
                        .includes(search)

                        ||

                        name.urdu
                        .toLowerCase()
                        .includes(search)

                        ||

                        name.arabic
                        .includes(search)

                        ||

                        String(name.number)
                        .includes(search)

                    );

                }
            );

    }


    if(showingFavorites){

        list =
            list.filter(
                function(name){

                    return favoriteNames.includes(
                        name.number
                    );

                }
            );

    }


    currentList =
        list;


    displayNames(
        currentList
    );

}


