// ===============================
// SEARCH DUA
// ===============================

function searchDua(){

let value = document
.getElementById("duaSearch")
.value
.toLowerCase();


let filtered = duas.filter(dua =>

dua.title.toLowerCase().includes(value) ||

dua.category.toLowerCase().includes(value) ||

dua.arabic.includes(value)

);


loadDuas(filtered);


}

// ===============================
// CATEGORY SYSTEM
// ===============================

function showCategory(category){

currentCategory = category;

let result = [];


if(category === "all"){


result = duas;


}



else if(category === "favorite"){


result = duas.filter((dua,index)=>{

return favorites.includes(index);

});


}



else{


result = duas.filter(dua=>{


return dua.category === category;


});


}


currentDuaList = result;
loadDuas(result);


}

