// ===============================
// LOAD DUAS
// ===============================

function loadDuas(list = duas){

window.currentDuaList = list;

const container = document.getElementById("duaList");

if(!container) return;

container.innerHTML = "";

list.forEach((dua)=>{

const realIndex = duas.indexOf(dua);

const fav =
favorites.includes(realIndex)
? "❤️"
: "🤍";

container.innerHTML += `

<div class="dua-card">

<div class="dua-header"
onclick="openReader(${realIndex})">

<h3>${dua.title}</h3>

<span>📖</span>

</div>

</div>

`;

});

}


// ===============================
// OPEN READER
// ===============================

function openReader(index){

currentDuaIndex = index;

const dua = duas[index];

document.getElementById("readerTitle").textContent = dua.title;

document.getElementById("readerArabic").textContent = dua.arabic;

document.getElementById("readerMeaning").textContent = dua.meaning;

document.getElementById("readerUrdu").textContent = dua.urdu;

document.getElementById("readerReference").textContent = dua.reference;

let currentPosition = currentDuaList.findIndex(
dua => dua === duas[index]
);


document.getElementById("readerCount").textContent =
(currentPosition + 1) + " / " + window.currentDuaList.length;

document.getElementById("readerFavBtn").innerHTML =
favorites.includes(index) ? "❤️" : "🤍";

document.getElementById("duaReader").classList.add("show");

document.querySelector(".reader-content").scrollTop = 0;

}





// ===============================
// COPY
// ===============================

function copyDua(index){

const dua = duas[index];

const text =

dua.title +

"\n\n" +

dua.arabic +

"\n\n" +

dua.meaning +

"\n\n" +

dua.urdu +

"\n\n" +

dua.reference;

navigator.clipboard.writeText(text)
.then(()=>{

alert("✅ Dua Copied");

})
.catch(()=>{

alert("Copy Failed");

});

}



