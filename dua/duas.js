// ===============================
// DUA SWIPE SYSTEM
// ===============================

let touchStartX = 0;

const reader = document.getElementById("duaReader");

if(reader){

reader.addEventListener("touchstart",function(e){

touchStartX = e.changedTouches[0].clientX;

});

reader.addEventListener("touchend",function(e){

const touchEndX = e.changedTouches[0].clientX;

if(touchStartX - touchEndX > 80){

nextDua();

}

else if(touchEndX - touchStartX > 80){

previousDua();

}

});

}


// ===============================
// NEXT DUA
// ===============================

function nextDua(){


let currentPosition = currentDuaList.findIndex(
dua => dua === duas[currentDuaIndex]
);



if(currentPosition < currentDuaList.length - 1){


let nextDuaItem = currentDuaList[currentPosition + 1];


currentDuaIndex = duas.indexOf(nextDuaItem);


openReader(currentDuaIndex);


}


}


// ===============================
// PREVIOUS DUA
// ===============================

function previousDua(){


let currentPosition = currentDuaList.findIndex(
dua => dua === duas[currentDuaIndex]
);



if(currentPosition > 0){


let previousDuaItem = currentDuaList[currentPosition - 1];


currentDuaIndex = duas.indexOf(previousDuaItem);


openReader(currentDuaIndex);


}


}

